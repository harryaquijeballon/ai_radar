"""Weekly outer-loop digest and handover reminder (plan 2026-11-09-001 U11).

Not a validator. Run weekly by `.github/workflows/handover-reminder.yml`,
which posts the digest as a GitHub issue when a handover is due. Everything
is derived from the repository (no state file, no model):

- delivered days and missed days, from the `radar: daily run <date>`
  commits of the last 7 days;
- whether each missed day has a write-up in `docs/ops/` (a file named
  `<date>-...incident....md`);
- scan turns and cost, from the commit trailers (`run_metrics.py`);
- the pending review-queue records and how many are near the length cap;
- the newest handover in `docs/hdai/` and its age.

`--github-output` receives `due=true|false`: a handover is due when the
newest one is at least `HANDOVER_DAYS` old.

Usage:
    python3 scripts/make_weekly_digest.py [--workspace .] [--today DATE]
"""

from __future__ import annotations

import argparse
import datetime
import os
import re
import statistics
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "validators"))

import lib_queues  # noqa: E402
import lib_radar  # noqa: E402
import make_queue_triage  # noqa: E402
import run_metrics  # noqa: E402

DAYS = 7
HANDOVER_DAYS = 7

_SUBJECT = re.compile(r"^radar: daily run (\d{4}-\d{2}-\d{2})$")
_TURNS = re.compile(r"^%s: (\d{1,6})$" % run_metrics.TURNS_TRAILER, re.M)
_COST = re.compile(r"^%s: (\d{1,4}\.\d{2})$" % run_metrics.COST_TRAILER, re.M)
_HANDOVER = re.compile(r"^(\d{4}-\d{2}-\d{2})_handover_(\d{3})_[a-z0-9_]+\.md$")


def delivered_runs(workspace: str):
    """{run date: (turns | None, cost | None)} from the commit history."""
    done = subprocess.run(
        ["git", "-C", workspace, "log", "-n", "400", "--format=%B%x00"],
        capture_output=True, text=True)
    runs = {}
    if done.returncode != 0:
        return runs
    for body in done.stdout.split("\x00"):
        body = body.strip()
        match = _SUBJECT.match(body.split("\n", 1)[0]) if body else None
        if not match or match.group(1) in runs:
            continue
        turns = _TURNS.search(body)
        cost = _COST.search(body)
        runs[match.group(1)] = (int(turns.group(1)) if turns else None,
                                float(cost.group(1)) if cost else None)
    return runs


def newest_handover(workspace: str):
    """(date, number, file name) of the newest handover, or None."""
    directory = os.path.join(workspace, "docs", "hdai")
    found = []
    if os.path.isdir(directory):
        for name in os.listdir(directory):
            match = _HANDOVER.match(name)
            date = lib_radar.parse_iso_date(match.group(1)) if match else None
            if date:
                found.append((date, int(match.group(2)), name))
    return max(found) if found else None


def writeup_for(workspace: str, day: str):
    directory = os.path.join(workspace, "docs", "ops")
    if not os.path.isdir(directory):
        return None
    names = sorted(name for name in os.listdir(directory)
                   if name.startswith(day) and name.endswith(".md")
                   and "incident" in name)
    return names[0] if names else None


def build_digest(workspace: str, today: datetime.date):
    """(markdown, handover due?)."""
    runs = delivered_runs(workspace)
    window = [(today - datetime.timedelta(days=offset)).isoformat()
              for offset in range(DAYS, 0, -1)]
    delivered = [day for day in window if day in runs]
    missed = [day for day in window if day not in runs]
    turns = [runs[day][0] for day in delivered if runs[day][0] is not None]
    costs = [runs[day][1] for day in delivered if runs[day][1] is not None]
    pending = make_queue_triage.pending_records(workspace)
    near_cap = [row for row in pending
                if row["headroom"] <= make_queue_triage.NEAR_CAP]
    handover = newest_handover(workspace)
    age = (today - handover[0]).days if handover else None
    due = handover is None or age >= HANDOVER_DAYS

    lines = ["Weekly outer-loop digest for the %d days to %s, generated by "
             "`scripts/make_weekly_digest.py`."
             % (DAYS, window[-1]), ""]
    lines.append("| measure | value |")
    lines.append("|---|---|")
    lines.append("| newest handover | %s |" % (
        "`docs/hdai/%s`, %d days old" % (handover[2], age) if handover
        else "none found"))
    lines.append("| handover due | %s |" % ("yes" if due else "no"))
    lines.append("| days delivered | %d of %d |" % (len(delivered), DAYS))
    lines.append("| days without a delivered run | %s |"
                 % (", ".join(missed) or "none"))
    lines.append("| scan turns (median) | %s |" % (
        "%d over %d runs" % (round(statistics.median(turns)), len(turns))
        if turns else "no data yet"))
    lines.append("| scan cost (total, USD) | %s |" % (
        "%.2f over %d runs" % (sum(costs), len(costs)) if costs
        else "no data yet"))
    lines.append("| review queue, pending | %d |" % len(pending))
    lines.append("| review queue, within %d characters of the cap | %d |"
                 % (make_queue_triage.NEAR_CAP, len(near_cap)))
    lines.append("")
    lines.append("To do:")
    lines.append("")
    if due:
        lines.append("- [ ] Write the weekly HDAI delta handover in "
                     "`docs/hdai/` (handover %03d)."
                     % ((handover[1] + 1) if handover else 1))
    for day in missed:
        note = writeup_for(workspace, day)
        lines.append("- [%s] %s had no delivered run: %s" % (
            "x" if note else " ", day,
            "write-up `docs/ops/%s`" % note if note
            else "no write-up in `docs/ops/` yet. Check the run log and "
                 "write one."))
    if pending:
        lines.append("- [ ] Resolve review-queue records, starting with the "
                     "%d near the cap (`python3 scripts/make_queue_triage.py`)."
                     % len(near_cap))
    lines.append("")
    return "\n".join(lines), due


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", default=".")
    parser.add_argument("--today", default=None)
    parser.add_argument("--github-output", default=None)
    args = parser.parse_args()
    today = (lib_radar.parse_iso_date(args.today) if args.today
             else lib_radar.london_today())
    if today is None:
        raise ValueError("--today is not an ISO date")
    digest, due = build_digest(args.workspace, today)
    if args.github_output:
        with open(args.github_output, "a", encoding="utf-8") as handle:
            handle.write("due=%s\n" % ("true" if due else "false"))
    sys.stdout.write(digest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
