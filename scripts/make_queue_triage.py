"""Queue triage sheet (plan 2026-11-09-001 U10).

Not a validator. A read-only generator for the user: every `pending` record
in `reviews/deferred_candidates/` and `reviews/source_proposals/`, ordered
by how close its grow-only text is to the length cap (`MAX_FREE_TEXT`),
then by age. A record at the cap is where the grow-only/length-cap
deadlock (P9) starts, so the top of the sheet is the place to begin.

The sheet is a view over the queue files, never a second source of truth:
only the user resolves a record, in the queue file itself, as
`engine/templates/deferred-candidate.md` and `source-proposal.md` describe.

Usage:
    python3 scripts/make_queue_triage.py [--workspace .] [--today YYYY-MM-DD]
"""

from __future__ import annotations

import argparse
import datetime
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "validators"))

import lib_queues  # noqa: E402
import lib_radar  # noqa: E402

NEAR_CAP = 15  # characters of headroom at or under which a record is urgent

RESOLUTIONS = {
    lib_queues.QUEUE_DEFERRED:
        "archived, provisional, rejected, dismissed or duplicate",
    lib_queues.QUEUE_PROPOSALS: "promoted, rejected or already_covered",
}


def _cell(value) -> str:
    return str(value if value is not None else "").replace("|", "\\|") \
        .replace("\n", " ").strip()


def pending_records(workspace: str):
    """One dict per pending record across the four queue files."""
    rows = []
    for kind in (lib_queues.QUEUE_DEFERRED, lib_queues.QUEUE_PROPOSALS):
        for domain in lib_radar.DOMAINS:
            rel = "reviews/%s/%s.md" % (kind, domain)
            path = os.path.join(workspace, rel)
            if not os.path.isfile(path):
                continue
            with open(path, encoding="utf-8") as handle:
                records, _ = lib_queues.parse_queue_file(handle.read())
            for record in records:
                fields = record.fields
                if fields.get("status") != "pending":
                    continue
                longest = max(
                    [(len(fields.get(name, "")), name)
                     for name in lib_queues.GROW_ONLY_UNATTENDED] or [(0, "")])
                first = fields.get("first_encountered") \
                    or fields.get("first_discovered")
                rows.append({
                    "kind": kind, "domain": domain, "rel": rel,
                    "line": record.line, "url": record.url, "fields": fields,
                    "headroom": lib_queues.MAX_FREE_TEXT - longest[0],
                    "longest_field": longest[1],
                    "first": first, "last": fields.get("last_encountered"),
                })
    return rows


def _age(row, today):
    first = lib_radar.parse_iso_date(str(row["first"] or ""))
    return (today - first).days if first else None


def build_sheet(workspace: str, today: datetime.date) -> str:
    rows = pending_records(workspace)
    rows.sort(key=lambda row: (row["headroom"], -(_age(row, today) or 0),
                               row["url"]))
    urgent = [row for row in rows if row["headroom"] <= NEAR_CAP]
    lines = ["# Review-queue triage sheet - %s" % today.isoformat(), ""]
    lines.append(
        "Generated by `scripts/make_queue_triage.py` from the queue files. "
        "**%d pending records**; **%d within %d characters of the %d-character"
        " cap** (the next re-encounter could push them over). Start at the top."
        % (len(rows), len(urgent), NEAR_CAP, lib_queues.MAX_FREE_TEXT))
    lines.append("")
    lines.append(
        "To resolve a record, edit it in its queue file: set `status`, and "
        "append `resolution_date`, `resolution` and `linked_ref` (deferred "
        "candidates) or fill `review_note` (source proposals). Never delete "
        "or rewrite a record. This sheet is a view; the queue files are the "
        "record.")
    lines.append("")
    lines.append("| # | headroom | age (days) | first / last seen | queue | "
                 "reason class | record | file |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for number, row in enumerate(rows, 1):
        fields = row["fields"]
        age = _age(row, today)
        label = _cell(fields.get("title") or fields.get("source_name")
                      or row["url"])
        lines.append("| %d | %d%s | %s | %s / %s | %s, %s | %s | [%s](%s) | "
                     "`%s:%d` |" % (
                         number, row["headroom"],
                         " **at cap**" if row["headroom"] <= 0 else "",
                         age if age is not None else "?",
                         _cell(row["first"]), _cell(row["last"]),
                         "deferred" if row["kind"] == lib_queues.QUEUE_DEFERRED
                         else "source proposal",
                         row["domain"],
                         _cell(fields.get("reason_class", "n/a")),
                         label, row["url"], row["rel"], row["line"]))
    lines.append("")
    lines.append("## Records")
    for number, row in enumerate(rows, 1):
        fields = row["fields"]
        lines.append("")
        lines.append("### %d. %s" % (number, _cell(
            fields.get("title") or fields.get("source_name") or row["url"])))
        lines.append("")
        lines.append("- URL: <%s>" % row["url"])
        lines.append("- File: `%s:%d`; headroom %d characters (longest field:"
                     " `%s`)" % (row["rel"], row["line"], row["headroom"],
                                 row["longest_field"]))
        for name in ("reason", "why_useful", "action_needed",
                     "proposed_purpose", "surfaced_by"):
            if fields.get(name):
                lines.append("- %s: %s" % (name, _cell(fields[name])))
        lines.append("- Resolve as: %s" % RESOLUTIONS[row["kind"]])
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", default=".")
    parser.add_argument("--today", default=None)
    args = parser.parse_args()
    today = (lib_radar.parse_iso_date(args.today) if args.today
             else lib_radar.london_today())
    if today is None:
        raise ValueError("--today is not an ISO date")
    sys.stdout.write(build_sheet(args.workspace, today))
    return 0


if __name__ == "__main__":
    sys.exit(main())
